/**
 * Cloudflare Worker — kraftykinni.in
 * ===================================
 * Combines two things:
 *
 * A) Security response headers on top of GitHub Pages (which cannot set
 *    custom headers itself). Fixes the 5 "Security" findings from
 *    seoscore.tools:
 *      - Missing X-Content-Type-Options header
 *      - No Content-Security-Policy header (real header, not meta)
 *      - Missing X-Frame-Options
 *      - No Referrer-Policy header (real header, not meta)
 *      - No Permissions-Policy
 *
 * B) Agent-readiness additions (isitagentready.com-style audit):
 *      - Markdown Negotiation: serves the pre-built .md twin (generated by
 *        scripts/prerender.mjs) instead of .html when a request's Accept
 *        header prefers text/markdown.
 *      - RFC 8288 Link headers: points agents at llms.txt and the Agent
 *        Skills discovery index on every HTML response.
 *
 * Deploy: Workers & Pages → your Worker → Edit code → paste this whole file
 * → Deploy. Route stays kraftykinni.in/* as already configured.
 */

function prefersMarkdown(request) {
  const accept = request.headers.get('Accept') || '';
  if (!accept.includes('text/markdown')) return false;
  const mdIndex = accept.indexOf('text/markdown');
  const htmlIndex = accept.indexOf('text/html');
  // Prefer markdown only if html isn't explicitly preferred ahead of it.
  return htmlIndex === -1 || mdIndex < htmlIndex;
}

function markdownPathFor(url) {
  let pathname = url.pathname;
  if (pathname === '/') return '/index.md';
  if (pathname.endsWith('/')) pathname = pathname.slice(0, -1);
  if (pathname.endsWith('.html')) pathname = pathname.slice(0, -5);
  return `${pathname}.md`;
}

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);

    // ── B1. Markdown Negotiation ──────────────────────────────────────────
    // Skip well-known/asset paths — they have no .md twin.
    if (
      request.method === 'GET' &&
      prefersMarkdown(request) &&
      !url.pathname.startsWith('/.well-known/') &&
      !url.pathname.startsWith('/assets/')
    ) {
      const mdUrl = new URL(markdownPathFor(url), url);
      const mdResponse = await fetch(mdUrl.toString(), request);
      if (mdResponse.ok) {
        const mdHeaders = new Headers(mdResponse.headers);
        mdHeaders.set('Content-Type', 'text/markdown; charset=utf-8');
        mdHeaders.set('Vary', 'Accept');
        return new Response(mdResponse.body, { status: mdResponse.status, headers: mdHeaders });
      }
      // No .md twin exists for this path — fall through to normal handling.
    }

    // ── A. Let GitHub Pages handle the actual request/response as normal ──
    const response = await fetch(request);

    // Clone so we can safely add headers to the response.
    const newResponse = new Response(response.body, response);

    newResponse.headers.set('X-Content-Type-Options', 'nosniff');
    newResponse.headers.set('X-Frame-Options', 'SAMEORIGIN');
    newResponse.headers.set('Referrer-Policy', 'strict-origin-when-cross-origin');
    newResponse.headers.set(
      'Permissions-Policy',
      'camera=(), microphone=(), geolocation=(), interest-cohort=()'
    );
    // Keep this in sync with the <meta http-equiv="Content-Security-Policy">
    // in index.html — same allowed origins (Google Fonts, GA, AdSense,
    // the Cloudflare image CDN, and the Web3Forms contact endpoint).
    newResponse.headers.set(
      'Content-Security-Policy',
      "default-src 'self'; " +
      "script-src 'self' 'unsafe-inline' https://www.googletagmanager.com https://pagead2.googlesyndication.com https://www.google-analytics.com https://static.cloudflareinsights.com https://*.adtrafficquality.google; " +
      "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; " +
      "font-src 'self' https://fonts.gstatic.com; " +
      "img-src 'self' data: https://cdn.kraftykinni.in https://www.google-analytics.com https://pagead2.googlesyndication.com https://*.googlesyndication.com https://*.adtrafficquality.google; " +
      "connect-src 'self' https://www.google-analytics.com https://api.web3forms.com https://pagead2.googlesyndication.com https://*.googlesyndication.com https://googleads.g.doubleclick.net https://static.cloudflareinsights.com https://*.adtrafficquality.google; " +
      "frame-src https://googleads.g.doubleclick.net https://pagead2.googlesyndication.com https://*.googlesyndication.com https://*.adtrafficquality.google https://www.google.com; " +
      "base-uri 'self'; form-action 'self' https://api.web3forms.com;"
    );

    // ── B2. RFC 8288 Link headers (agent discovery) ───────────────────────
    const contentType = newResponse.headers.get('Content-Type') || '';
    if (contentType.includes('text/html')) {
      const agentLinks = [
        '<https://kraftykinni.in/llms.txt>; rel="alternate"; type="text/markdown"',
        '<https://kraftykinni.in/.well-known/agent-skills/index.json>; rel="service-desc"',
      ].join(', ');
      const existingLink = newResponse.headers.get('Link');
      newResponse.headers.set('Link', existingLink ? `${existingLink}, ${agentLinks}` : agentLinks);
      newResponse.headers.append('Vary', 'Accept');
    }

    return newResponse;
  },
};
